const MAX_AVATAR_BYTES = 5 * 1024 * 1024;
const AVATAR_MIME_TYPES = new Set([
  'image/jpeg',
  'image/png',
  'image/gif',
  'image/webp',
]);
const AVATAR_EXTENSIONS = new Set(['jpg', 'jpeg', 'png', 'gif', 'webp']);

// This matches User.to_dict(). The UI only updates the authenticated store after it
// receives this complete representation, never after a partial avatar response.
const REQUIRED_USER_FIELDS = [
  'id',
  'email',
  'first_name',
  'last_name',
  'phone',
  'country_code',
  'is_active',
  'is_verified',
  'two_factor_enabled',
  'kyc_status',
  'role',
  'tenant_id',
  'avatar_url',
  'created_at',
  'last_login_at',
];

export const PROFILE_EDITABLE_FIELDS = Object.freeze([
  'first_name',
  'last_name',
  'phone',
]);

export class ProfileContractError extends Error {
  constructor(message) {
    super(message);
    this.name = 'ProfileContractError';
  }
}

const isRecord = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);
const isScalarId = (value) => (
  (typeof value === 'string' && value.trim().length > 0)
  || (typeof value === 'number' && Number.isFinite(value))
);
const isNullableString = (value) => value === null || typeof value === 'string';
const canonicalId = (value) => `${typeof value}:${String(value)}`;

export const tenantIdFromUser = (user) => {
  if (!isRecord(user)) return undefined;
  if (user.tenant_id !== undefined) return user.tenant_id;
  if (user.tenantId !== undefined) return user.tenantId;
  if (isRecord(user.tenant) && user.tenant.id !== undefined) return user.tenant.id;
  return undefined;
};

/**
 * A local user object is only an identity hint. It is intentionally insufficient
 * to populate the page: getProfile() always obtains authoritative display data.
 */
export const profilePrincipalFromUser = (user, isAuthenticated) => {
  if (!isAuthenticated || !isRecord(user)) return null;

  const tenantId = tenantIdFromUser(user);
  if (!isScalarId(user.id) || !(tenantId === null || isScalarId(tenantId)) || typeof user.role !== 'string' || !user.role.trim()) {
    return null;
  }

  const role = user.role.trim();
  return {
    id: user.id,
    tenantId,
    role,
    key: JSON.stringify([true, canonicalId(user.id), canonicalId(tenantId), role]),
  };
};

const browserOrigin = () => (
  typeof window !== 'undefined' && window.location?.origin
    ? window.location.origin
    : 'https://profile.invalid'
);

/**
 * Avatar URLs may be the backend's local /uploads/profiles path or the precise
 * public DigitalOcean Spaces CDN shape generated by StorageService. No other
 * origin, credential-bearing URL, or scheme is rendered or accepted as success.
 */
export const isSafeAvatarUrl = (value, origin = browserOrigin()) => {
  if (typeof value !== 'string' || !value.trim()) return false;
  const raw = value.trim();

  try {
    const parsed = new URL(raw, origin);
    if (parsed.username || parsed.password) return false;

    if (parsed.origin === origin) {
      return raw.startsWith('/uploads/profiles/')
        && parsed.protocol === new URL(origin).protocol
        && parsed.pathname.startsWith('/uploads/profiles/');
    }

    return parsed.protocol === 'https:'
      && /^[a-z0-9][a-z0-9-]*\.[a-z0-9-]+\.cdn\.digitaloceanspaces\.com$/i.test(parsed.hostname)
      && parsed.pathname.startsWith('/profiles/');
  } catch {
    return false;
  }
};

export const safeAvatarUrl = (value, origin = browserOrigin()) => (
  isSafeAvatarUrl(value, origin) ? value.trim() : null
);

export const validateAvatarFile = (file) => {
  if (!isRecord(file) || typeof file.name !== 'string') {
    return { valid: false, message: 'Select an image file before uploading.' };
  }

  const extension = file.name.split('.').pop()?.toLowerCase();
  if (!extension || !AVATAR_EXTENSIONS.has(extension)) {
    return { valid: false, message: 'Use a JPG, PNG, GIF, or WEBP image.' };
  }

  if (!AVATAR_MIME_TYPES.has(file.type)) {
    return { valid: false, message: 'The selected file MIME type is not supported.' };
  }

  if (!Number.isSafeInteger(file.size) || file.size <= 0 || file.size > MAX_AVATAR_BYTES) {
    return { valid: false, message: 'Image files must be 5 MiB or smaller.' };
  }

  return { valid: true };
};

export const personalDraftFromUser = (user) => ({
  first_name: typeof user?.first_name === 'string' ? user.first_name : '',
  last_name: typeof user?.last_name === 'string' ? user.last_name : '',
  phone: typeof user?.phone === 'string' ? user.phone : '',
});

export const personalPayloadFromDraft = (draft) => ({
  first_name: String(draft?.first_name ?? '').trim(),
  last_name: String(draft?.last_name ?? '').trim(),
  phone: String(draft?.phone ?? '').trim(),
});

const assertCompleteUser = (user, expectedPrincipal, endpoint) => {
  if (!isRecord(user)) {
    throw new ProfileContractError(`${endpoint} did not include a user object.`);
  }

  const missingFields = REQUIRED_USER_FIELDS.filter((field) => !(field in user));
  if (missingFields.length) {
    throw new ProfileContractError(`${endpoint} returned an incomplete user: ${missingFields.join(', ')}.`);
  }

  if (!isScalarId(user.id) || !(user.tenant_id === null || isScalarId(user.tenant_id))) {
    throw new ProfileContractError(`${endpoint} returned an invalid user identity.`);
  }
  if (!expectedPrincipal
    || canonicalId(user.id) !== canonicalId(expectedPrincipal.id)
    || canonicalId(user.tenant_id) !== canonicalId(expectedPrincipal.tenantId)) {
    throw new ProfileContractError(`${endpoint} returned a different account.`);
  }

  if (typeof user.email !== 'string' || !user.email.trim()
    || typeof user.first_name !== 'string'
    || typeof user.last_name !== 'string'
    || typeof user.role !== 'string' || !user.role.trim()
    || !isNullableString(user.phone)
    || !isNullableString(user.country_code)
    || !isNullableString(user.kyc_status)
    || !isNullableString(user.avatar_url)
    || !isNullableString(user.created_at)
    || !isNullableString(user.last_login_at)
    || typeof user.is_active !== 'boolean'
    || typeof user.is_verified !== 'boolean'
    || typeof user.two_factor_enabled !== 'boolean') {
    throw new ProfileContractError(`${endpoint} returned malformed user fields.`);
  }

  if (user.avatar_url !== null && !isSafeAvatarUrl(user.avatar_url)) {
    throw new ProfileContractError(`${endpoint} returned an unsafe avatar URL.`);
  }

  return user;
};

const responseBody = (response, endpoint) => {
  if (!isRecord(response) || !isRecord(response.data)) {
    throw new ProfileContractError(`${endpoint} returned an invalid response.`);
  }
  return response.data;
};

const readUserResponse = (response, expectedPrincipal, endpoint, { requireMessage = false } = {}) => {
  const data = responseBody(response, endpoint);
  if (requireMessage && (typeof data.message !== 'string' || !data.message.trim())) {
    throw new ProfileContractError(`${endpoint} did not confirm the completed action.`);
  }
  return { data, user: assertCompleteUser(data.user, expectedPrincipal, endpoint) };
};

const call = (method, args) => {
  if (typeof method !== 'function') {
    return Promise.reject(new ProfileContractError('Profile API contract is unavailable.'));
  }
  try {
    return Promise.resolve(method(...args));
  } catch (error) {
    return Promise.reject(error);
  }
};

/**
 * Maps the established shared profileAPI onto an inspectable request contract.
 * profileAPI currently owns the real endpoint construction; this adapter keeps
 * that ownership while allowing focused tests to assert path/payload/signal.
 */
export const createProfileApiTransport = (profileApi) => ({
  request: ({ method, path, data, signal }) => {
    const options = { signal };
    if (method === 'GET' && path === '/profile') return profileApi?.get(options);
    if (method === 'PUT' && path === '/profile') return profileApi?.update(data, options);
    if (method === 'POST' && path === '/profile/avatar') return profileApi?.uploadAvatar(data, options);
    if (method === 'DELETE' && path === '/profile/avatar') return profileApi?.deleteAvatar(options);
    if (method === 'PUT' && path === '/profile/password') return profileApi?.changePassword(data, options);
    throw new ProfileContractError(`Unsupported profile request: ${method} ${path}`);
  },
});

const abortError = () => {
  const error = new Error('Profile request was cancelled.');
  error.name = 'AbortError';
  return error;
};

// The shared transport forwards AbortSignal to Axios. Also race it with cancellation
// so an adapter ignoring abort cannot publish an old response; component refs form
// the second guard before any state/store/navigation side effect.
const observeAbort = (promise, signal) => {
  if (!signal) return promise;
  if (signal.aborted) return Promise.reject(abortError());
  return new Promise((resolve, reject) => {
    const onAbort = () => reject(abortError());
    signal.addEventListener('abort', onAbort, { once: true });
    promise.then(resolve, reject).finally(() => signal.removeEventListener('abort', onAbort));
  });
};

const requestProfile = (transport, request) => observeAbort(
  call(transport?.request, [request]),
  request.signal,
);

/**
 * The dependency exposes request({ method, path, data, signal }). Paths remain
 * explicit for contract tests. The default adapter calls existing profileAPI
 * methods (including profileAPI.update) and forwards the optional signal.
 */
export const createProfileViewService = (transport) => ({
  getProfile: async (expectedPrincipal, signal) => {
    const response = await requestProfile(transport, { method: 'GET', path: '/profile', signal });
    return readUserResponse(response, expectedPrincipal, 'Profile', { requireMessage: false });
  },

  updateProfile: async (draft, expectedPrincipal, signal) => {
    const payload = personalPayloadFromDraft(draft);
    const response = await requestProfile(transport, { method: 'PUT', path: '/profile', data: payload, signal });
    const result = readUserResponse(response, expectedPrincipal, 'Profile update', { requireMessage: true });
    return { ...result, payload };
  },

  uploadAvatar: async (file, expectedPrincipal, signal) => {
    const preflight = validateAvatarFile(file);
    if (!preflight.valid) throw new ProfileContractError(preflight.message);

    const response = await requestProfile(transport, { method: 'POST', path: '/profile/avatar', data: file, signal });
    const result = readUserResponse(response, expectedPrincipal, 'Avatar upload', { requireMessage: true });
    if (typeof result.data.avatar_url !== 'string'
      || !isSafeAvatarUrl(result.data.avatar_url)
      || result.data.avatar_url !== result.user.avatar_url) {
      throw new ProfileContractError('Avatar upload returned an unsafe or inconsistent avatar URL.');
    }
    return { ...result, avatarUrl: result.data.avatar_url };
  },

  deleteAvatar: async (expectedPrincipal, signal) => {
    const response = await requestProfile(transport, { method: 'DELETE', path: '/profile/avatar', signal });
    const result = readUserResponse(response, expectedPrincipal, 'Avatar deletion', { requireMessage: true });
    if (result.user.avatar_url !== null) {
      throw new ProfileContractError('Avatar deletion did not return a cleared avatar URL.');
    }
    return result;
  },

  changePassword: async (passwords, signal) => {
    const payload = {
      current_password: String(passwords?.current_password ?? ''),
      new_password: String(passwords?.new_password ?? ''),
    };
    const response = await requestProfile(transport, { method: 'PUT', path: '/profile/password', data: payload, signal });
    const data = responseBody(response, 'Password change');
    if (data.message !== 'Password changed successfully') {
      throw new ProfileContractError('Password change did not confirm the completed action.');
    }
    return { data, payload };
  },
});

export const profileErrorMessage = (error, fallback) => {
  if (error instanceof ProfileContractError && error.message) return error.message;
  const message = error?.response?.data?.error ?? error?.response?.data?.message;
  return typeof message === 'string' && message.trim() ? message : fallback;
};

export const isAbortError = (error) => (
  error?.name === 'AbortError' || error?.code === 'ERR_CANCELED' || error?.__CANCEL__ === true
);

export { MAX_AVATAR_BYTES };
